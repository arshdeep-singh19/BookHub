CREATE TABLE books (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR2(255) NOT NULL,
    author VARCHAR2(255) NOT NULL,
    genre VARCHAR2(100),
    price NUMBER(10, 2) NOT NULL,
    published_year NUMBER(4),
    isbn VARCHAR2(50),
    description CLOB
);

