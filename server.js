const express = require('express');
const cors = require('cors');
const path = require('path');
const oracledb = require('oracledb');
require('dotenv').config();

const app = express();
const PORT = process.env.PORT || 3000;

app.use(cors());
app.use(express.json());
app.use(express.static(path.join(__dirname, 'public')));

// Configure Oracle to return rows as JavaScript objects and CLOBs as strings
oracledb.outFormat = oracledb.OUT_FORMAT_OBJECT;
oracledb.fetchAsString = [oracledb.CLOB];

const dbConfig = {
    user: process.env.DB_USER || 'system',
    password: process.env.DB_PASSWORD || 'password',
    connectString: process.env.DB_CONNECT_STRING || 'localhost:1521/XEPDB1'
};

let useFallbackMemory = false;
let fallbackBooks = [
    { ID: 1, TITLE: 'The Pragmatic Programmer', AUTHOR: 'Andrew Hunt & David Thomas', GENRE: 'Technology', PRICE: 45.99, PUBLISHED_YEAR: 1999, ISBN: '978-0201616224', DESCRIPTION: 'A classic guide to software craftsmanship and pragmatic software development.' },
    { ID: 2, TITLE: 'Clean Code', AUTHOR: 'Robert C. Martin', GENRE: 'Technology', PRICE: 39.99, PUBLISHED_YEAR: 2008, ISBN: '978-0132350884', DESCRIPTION: 'A handbook of agile software craftsmanship covering best practices for writing clean code.' },
    { ID: 3, TITLE: 'Dune', AUTHOR: 'Frank Herbert', GENRE: 'Sci-Fi', PRICE: 24.50, PUBLISHED_YEAR: 1965, ISBN: '978-0441172719', DESCRIPTION: 'Set on the desert planet Arrakis, Dune is the story of the boy Paul Atreides.' },
    { ID: 4, TITLE: 'The Alchemist', AUTHOR: 'Paulo Coelho', GENRE: 'Fiction', PRICE: 350, PUBLISHED_YEAR: 1988, ISBN: '978-0061122415', DESCRIPTION: 'Journey story' },
    { ID: 5, TITLE: 'Atomic Habits', AUTHOR: 'James Clear', GENRE: 'Self Help', PRICE: 400, PUBLISHED_YEAR: 2018, ISBN: '978-0735211292', DESCRIPTION: 'Habits book' },
    { ID: 6, TITLE: 'Wings of Fire', AUTHOR: 'APJ Abdul Kalam', GENRE: 'Biography', PRICE: 299, PUBLISHED_YEAR: 1999, ISBN: '978-8173711466', DESCRIPTION: 'Biography of APJ Kalam' }
];
let nextFallbackId = 7;

async function initDB() {
    let connection;
    try {
        connection = await oracledb.getConnection(dbConfig);
        console.log('Connected to Oracle Database successfully.');
        
        await connection.execute(`
            DECLARE
                table_exists NUMBER;
            BEGIN
                SELECT COUNT(*) INTO table_exists FROM user_tables WHERE table_name = 'BOOKS';
                IF table_exists = 0 THEN
                    EXECUTE IMMEDIATE '
                        CREATE TABLE books (
                            id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            title VARCHAR2(255) NOT NULL,
                            author VARCHAR2(255) NOT NULL,
                            genre VARCHAR2(100),
                            price NUMBER(10, 2) NOT NULL,
                            published_year NUMBER(4),
                            isbn VARCHAR2(50),
                            description CLOB
                        )';
                END IF;
            END;
        `);
    } catch (err) {
        console.warn('------------------------------------------------------------------');
        console.warn('WARNING: Could not connect to Oracle DB (' + err.message + ')');
        console.warn('Running in Fallback In-Memory Mode so the app works immediately.');
        console.warn('Update .env with your Oracle credentials to switch to Oracle DB.');
        console.warn('------------------------------------------------------------------');
        useFallbackMemory = true;
    } finally {
        if (connection) {
            try { await connection.close(); } catch (e) { console.error(e); }
        }
    }
}

// 1. Browse & Search Books (GET /api/books?q=search_term)
app.get('/api/books', async (req, res) => {
    const search = (req.query.q || '').trim().toLowerCase();
    if (useFallbackMemory) {
        const results = fallbackBooks.filter(b =>
            b.TITLE.toLowerCase().includes(search) || b.AUTHOR.toLowerCase().includes(search)
        );
        return res.json(results);
    }
    let connection;
    try {
        connection = await oracledb.getConnection(dbConfig);
        let query = `SELECT * FROM books ORDER BY id DESC`;
        let binds = {};
        if (search) {
            query = `SELECT * FROM books WHERE LOWER(title) LIKE :search OR LOWER(author) LIKE :search ORDER BY id DESC`;
            binds = { search: `%${search}%` };
        }
        const result = await connection.execute(query, binds);
        res.json(result.rows);
    } catch (err) {
        res.status(500).json({ error: err.message });
    } finally {
        if (connection) await connection.close();
    }
});

// 2. Admin Dashboard Stats (GET /api/stats)
app.get('/api/stats', async (req, res) => {
    if (useFallbackMemory) {
        return res.json({ totalBooks: fallbackBooks.length, dbMode: 'In-Memory Fallback (Configure .env for Oracle)' });
    }
    let connection;
    try {
        connection = await oracledb.getConnection(dbConfig);
        const result = await connection.execute(`SELECT COUNT(*) AS TOTAL FROM books`);
        res.json({ totalBooks: result.rows[0].TOTAL, dbMode: 'Oracle Database Connected' });
    } catch (err) {
        res.status(500).json({ error: err.message });
    } finally {
        if (connection) await connection.close();
    }
});

// 3. Book Details (GET /api/books/:id)
app.get('/api/books/:id', async (req, res) => {
    const bookId = Number(req.params.id);
    if (useFallbackMemory) {
        const book = fallbackBooks.find(b => b.ID === bookId);
        return book ? res.json(book) : res.status(404).json({ error: 'Book not found' });
    }
    let connection;
    try {
        connection = await oracledb.getConnection(dbConfig);
        const result = await connection.execute(`SELECT * FROM books WHERE id = :id`, [bookId]);
        if (result.rows.length === 0) return res.status(404).json({ error: 'Book not found' });
        res.json(result.rows[0]);
    } catch (err) {
        res.status(500).json({ error: err.message });
    } finally {
        if (connection) await connection.close();
    }
});

// 4. Add Book (POST /api/books)
app.post('/api/books', async (req, res) => {
    const { title, author, genre, price, published_year, isbn, description } = req.body;
    if (!title || !author || price === undefined) {
        return res.status(400).json({ error: 'Title, Author, and Price are required.' });
    }
    if (useFallbackMemory) {
        const newBook = {
            ID: nextFallbackId++,
            TITLE: title,
            AUTHOR: author,
            GENRE: genre || 'General',
            PRICE: Number(price),
            PUBLISHED_YEAR: Number(published_year) || new Date().getFullYear(),
            ISBN: isbn || 'N/A',
            DESCRIPTION: description || ''
        };
        fallbackBooks.unshift(newBook);
        return res.status(201).json({ message: 'Book added successfully', book: newBook });
    }
    let connection;
    try {
        connection = await oracledb.getConnection(dbConfig);
        await connection.execute(
            `INSERT INTO books (title, author, genre, price, published_year, isbn, description)
             VALUES (:title, :author, :genre, :price, :published_year, :isbn, :description)`,
            {
                title,
                author,
                genre: genre || 'General',
                price: Number(price),
                published_year: published_year ? Number(published_year) : null,
                isbn: isbn || '',
                description: description || ''
            },
            { autoCommit: true }
        );
        res.status(201).json({ message: 'Book added to Oracle DB successfully' });
    } catch (err) {
        res.status(500).json({ error: err.message });
    } finally {
        if (connection) await connection.close();
    }
});

// 5. Update Book (PUT /api/books/:id)
app.put('/api/books/:id', async (req, res) => {
    const bookId = Number(req.params.id);
    const { title, author, genre, price, published_year, isbn, description } = req.body;
    if (useFallbackMemory) {
        const idx = fallbackBooks.findIndex(b => b.ID === bookId);
        if (idx === -1) return res.status(404).json({ error: 'Book not found' });
        fallbackBooks[idx] = { ID: bookId, TITLE: title, AUTHOR: author, GENRE: genre || 'General', PRICE: Number(price), PUBLISHED_YEAR: Number(published_year), ISBN: isbn || '', DESCRIPTION: description || '' };
        return res.json({ message: 'Book updated successfully' });
    }
    let connection;
    try {
        connection = await oracledb.getConnection(dbConfig);
        await connection.execute(
            `UPDATE books SET title = :title, author = :author, genre = :genre, price = :price, published_year = :published_year, isbn = :isbn, description = :description WHERE id = :id`,
            { title, author, genre, price: Number(price), published_year: published_year ? Number(published_year) : null, isbn, description, id: bookId },
            { autoCommit: true }
        );
        res.json({ message: 'Book updated successfully' });
    } catch (err) {
        res.status(500).json({ error: err.message });
    } finally {
        if (connection) await connection.close();
    }
});

// 6. Delete Book (DELETE /api/books/:id)
app.delete('/api/books/:id', async (req, res) => {
    const bookId = Number(req.params.id);
    if (useFallbackMemory) {
        fallbackBooks = fallbackBooks.filter(b => b.ID !== bookId);
        return res.json({ message: 'Book deleted successfully' });
    }
    let connection;
    try {
        connection = await oracledb.getConnection(dbConfig);
        await connection.execute(`DELETE FROM books WHERE id = :id`, [bookId], { autoCommit: true });
        res.json({ message: 'Book deleted successfully' });
    } catch (err) {
        res.status(500).json({ error: err.message });
    } finally {
        if (connection) await connection.close();
    }
});

const { exec } = require('child_process');
initDB().then(() => {
    app.listen(PORT, () => {
        console.log(`BookHub Server running at http://localhost:${PORT}`);
        exec(`start http://localhost:${PORT}`);
    });
});